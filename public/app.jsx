function CustomerAssistant({ t, stations, onUseJourney }) {
  const [open, setOpen] = useState(false);
  const [draft, setDraft] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [messages, setMessages] = useState([]);
  const endRef = React.useRef(null);

  useEffect(() => { endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" }); }, [messages, busy, open]);

  const send = async (event) => {
    event?.preventDefault();
    const content = draft.trim();
    if (!content || busy) return;
    const next = [...messages, { role: "user", content }];
    setMessages(next);
    setDraft("");
    setError("");
    setBusy(true);
    try {
      const result = await api("/assistant/chat", { method: "POST", body: { messages: next.slice(-10) } });
      setMessages((current) => [...current, { role: "assistant", content: result.reply, journey: result.journey || null }]);
    } catch (e) { setError(e.message.includes("GEMINI_API_KEY") ? "AI assistant setup required. Add GEMINI_API_KEY to the server environment." : e.message); }
    finally { setBusy(false); }
  };

  const suggestions = ["How do I book a ticket?", "ঢাকা থেকে চট্টগ্রাম যেতে চাই", "How do I check my booking?"];
  const stationName = (code) => stations.find((item) => item.station_code === code)?.city || code;

  return <>
    {open && <section className={`assistant-panel fixed z-50 flex flex-col overflow-hidden rounded-2xl border shadow-2xl ${t.cardBg}`} aria-label="RailX customer assistant">
      <header className="flex items-center justify-between bg-brand px-4 py-3 text-white">
        <div><p className="font-bold">RailX assistant</p><p className="text-xs text-white/80">বাংলা ও English · Journey help</p></div>
        <button onClick={() => setOpen(false)} aria-label="Close assistant" className="rounded-lg px-2 py-1 text-xl text-white hover:bg-white/15">×</button>
      </header>
      <div className="assistant-messages flex-1 space-y-3 overflow-y-auto p-4" aria-live="polite">
        {messages.length === 0 && <div>
          <div className="assistant-bubble assistant-answer rounded-2xl rounded-tl-sm px-3.5 py-3 text-sm">Hello! আমি আপনাকে ট্রেন খুঁজতে, বুকিং বুঝতে বা টিকিট সংক্রান্ত প্রশ্নে সাহায্য করতে পারি। কীভাবে সাহায্য করব?</div>
          <div className="mt-3 flex flex-wrap gap-2">{suggestions.map((item) => <button key={item} onClick={() => setDraft(item)} className={`rounded-full border px-3 py-1.5 text-xs ${t.primaryOutline}`}>{item}</button>)}</div>
        </div>}
        {messages.map((message, index) => <div key={`${message.role}-${index}`} className={`flex ${message.role === "user" ? "justify-end" : "justify-start"}`}>
          <div className={`assistant-bubble max-w-[88%] rounded-2xl px-3.5 py-3 text-sm leading-relaxed ${message.role === "user" ? "assistant-question rounded-tr-sm" : `assistant-answer rounded-tl-sm ${t.text}`}`}>
            <p className="whitespace-pre-wrap">{message.content}</p>
            {message.journey && <div className={`mt-3 rounded-xl border p-3 ${t.cardAltBg}`}>
              <p className={`font-semibold ${t.text}`}>{stationName(message.journey.from)} → {stationName(message.journey.to)}</p>
              {message.journey.date && <p className={`mt-1 text-xs ${t.subtext}`}>Date: {message.journey.date}</p>}
              {message.journey.coach && <p className={`mt-1 text-xs ${t.subtext}`}>Class: {message.journey.coach}</p>}
              <button onClick={() => { onUseJourney(message.journey); setOpen(false); }} className="mt-3 w-full rounded-lg bg-brand px-3 py-2 text-xs font-bold text-white">Use this journey</button>
            </div>}
          </div>
        </div>)}
        {busy && <div className={`text-xs ${t.subtext}`} role="status">Assistant is replying…</div>}
        {error && <div className="rounded-xl bg-red-50 px-3 py-2 text-xs text-red-700" role="alert">{error}</div>}
        <div ref={endRef} />
      </div>
      <form onSubmit={send} className={`flex items-end gap-2 border-t p-3 ${t.divider}`}>
        <textarea value={draft} onChange={(event) => setDraft(event.target.value)} onKeyDown={(event) => { if (event.key === "Enter" && !event.shiftKey) { event.preventDefault(); send(); } }} rows={1} maxLength={1200} placeholder="Ask in বাংলা or English…" aria-label="Message the assistant" className={`max-h-24 min-h-10 flex-1 resize-y rounded-xl border px-3 py-2.5 text-sm ${t.inputBg}`} />
        <button type="submit" disabled={busy || !draft.trim()} className="h-10 rounded-xl bg-brand px-4 text-sm font-bold text-white disabled:opacity-50">Send</button>
      </form>
    </section>}
    <button onClick={() => setOpen((value) => !value)} aria-expanded={open} aria-label={open ? "Close customer assistant" : "Open customer assistant"} className="assistant-launcher fixed z-40 flex items-center gap-2 rounded-full bg-brand px-5 py-3.5 font-bold text-white shadow-lg">
      <span aria-hidden="true">✦</span><span>Ask RailX</span>
    </button>
  </>;
}

function App() {
  const { theme, setTheme, t } = useTheme();
  const [page, setPage] = useState(pageFromLocation);
  const [currentUser, setCurrentUser] = useState(null);
  const [authChecked, setAuthChecked] = useState(false);
  const [pendingSearch, setPendingSearch] = useState(null);
  const [pendingPage, setPendingPage] = useState(null);
  const [stations, setStations] = useState([]);
  const [classTypes, setClassTypes] = useState([]);
  const [search, setSearch] = useState({ from: "DHK", to: "CTG", date: todayISO(), klass: "" });
  const [searchError, setSearchError] = useState("");
  const [ctx, setCtx] = useState({});

  useEffect(() => {
    api("/stations", { auth: false }).then(setStations).catch(() => setStations([]));
    api("/classes", { auth: false }).then((cs) => setClassTypes(cs.map((c) => c.coach_type))).catch(() => setClassTypes([]));
    api("/auth/me").then((d) => setCurrentUser(d.user)).catch(() => setCurrentUser(null)).finally(() => setAuthChecked(true));
  }, []);

  const go = (p, patch, opts = {}) => {
    setCtx((c) => ({ ...c, ...(patch || {}) }));
    setPage(p);
    // Keep the address bar in sync with in-app navigation so every page the
    // app can show also has a real, bookmarkable/shareable URL.
    const path = ROUTE_PATHS[p] || "/";
    if (window.location.pathname !== path) {
      if (opts.replace) window.history.replaceState({}, "", path);
      else window.history.pushState({}, "", path);
    }
    window.scrollTo(0, 0);
  };

  const goAnchor = (id) => {
    const scroll = () => document.getElementById(id)?.scrollIntoView({ behavior: "smooth", block: "start" });
    if (page !== "home") { go("home"); window.setTimeout(scroll, 120); }
    else scroll();
  };

  // Support the browser's Back/Forward buttons.
  useEffect(() => {
    const onPopState = () => setPage(pageFromLocation());
    window.addEventListener("popstate", onPopState);
    return () => window.removeEventListener("popstate", onPopState);
  }, []);

  // Route guard: runs whenever the page or auth state changes, and is the
  // enforcement point for "no admin page without authorization". It redirects
  // (rather than merely hiding content) so a customer typing /admin directly
  // into the address bar — not just clicking a hidden nav link — never lands
  // on the admin dashboard. The admin API itself is independently protected
  // server-side (requireAuth + a fresh DB role check in requireAdmin), so
  // this is defense in depth, not the only guard.
  useEffect(() => {
    if (!authChecked) return;
    if (AUTH_ONLY_PAGES.has(page) && !currentUser) {
      if (page === "contact") setPendingPage("contact");
      go("login", {}, { replace: true });
      return;
    }
    if (ADMIN_ONLY_PAGES.has(page) && currentUser?.role !== "admin") {
      go("home", {}, { replace: true });
      return;
    }
    if (CUSTOMER_ONLY_PAGES.has(page) && currentUser?.role !== "customer") {
      go("home", {}, { replace: true });
      return;
    }
    if (CONTEXT_ONLY_PAGES.has(page)) {
      const missing =
        (page === "coach" && !ctx.tripId) ||
        (page === "seats" && !ctx.coach) ||
        (page === "passenger" && !ctx.seats) ||
        ((page === "payment" || page === "ticket") && !ctx.booking);
      if (missing) go("home", {}, { replace: true });
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [page, authChecked, currentUser?.user_id, currentUser?.role]);

  // Restore an in-progress payment after a browser refresh. A PNR in
  // sessionStorage is only a pointer; the API enforces the actual ownership.
  useEffect(() => {
    if (!authChecked || !currentUser) return;
    const pnr = sessionStorage.getItem(PENDING_BOOKING_KEY);
    if (!pnr) return;

    api(`/bookings/${encodeURIComponent(pnr)}`)
      .then((full) => {
        if (full.booking.effective_status !== "pending") {
          sessionStorage.removeItem(PENDING_BOOKING_KEY);
          return;
        }
        go("payment", { booking: full, fromMyBookings: false }, { replace: true });
      })
      .catch(() => sessionStorage.removeItem(PENDING_BOOKING_KEY));
  }, [authChecked, currentUser?.user_id]);

  const validateSearch = () => {
    if (!search.from || !search.to) return "Please choose both a departure and destination station.";
    if (search.from === search.to) return "Departure and destination stations must be different.";
    if (!search.date) return "Please choose a journey date.";
    if (search.date < todayISO()) return "Journey date cannot be in the past.";
    return "";
  };

  const doSearch = () => {
    const err = validateSearch();
    if (err) { setSearchError(err); return; }
    setSearchError("");
    if (!currentUser) { setPendingSearch({ ...search }); go("login"); return; }
    go("results");
  };

  const onLogin = (user) => {
    setCurrentUser(user);
    if (pendingSearch) { setSearch(pendingSearch); setPendingSearch(null); go("results"); }
    else if (pendingPage) { const destination = pendingPage; setPendingPage(null); go(destination); }
    else go("home");
  };

  const logout = async () => {
    try { await api("/auth/logout", { method: "POST" }); }
    catch (e) { /* Local state still must not retain an authenticated user. */ }
    setCurrentUser(null);
    go("home");
  };

  const useAssistantJourney = (journey) => {
    setSearch((current) => ({ ...current, from: journey.from, to: journey.to, date: journey.date || current.date, klass: journey.coach || "" }));
    go("home");
    window.setTimeout(() => document.getElementById("search-card")?.scrollIntoView({ behavior: "smooth", block: "center" }), 140);
  };

  // Enrich ctx with station city names + derived fields whenever we move
  // into the coach/seat/passenger/payment flow, so downstream pages don't
  // each have to re-derive them.
  const goBooking = (p, patch) => {
    const enriched = { ...patch };
    if (patch && (patch.tripId !== undefined || page === "results")) {
      enriched.search = {
        from: search.from, to: search.to,
        fromCity: stations.find((s) => s.station_code === search.from)?.city,
        toCity: stations.find((s) => s.station_code === search.to)?.city,
      };
    }
    go(p, enriched);
  };

  let body;
  if (!authChecked) {
    body = <div className="max-w-4xl mx-auto px-4 py-16 text-center text-sm text-neutral-400">Loading…</div>;
  } else if (page === "home") {
    body = <HomePage t={t} search={search} setSearch={setSearch} doSearch={doSearch} searchError={searchError} stations={stations} classTypes={classTypes} go={go} onAnchor={goAnchor} />;
  } else if (page === "login") {
    body = <LoginPage t={t} pendingSearch={pendingSearch} onLogin={onLogin} stations={stations} />;
  } else if (page === "results") {
    body = <ResultsPage t={t} search={search} go={goBooking} stations={stations} currentUser={currentUser} />;
  } else if (page === "coach" && ctx.tripId) {
    body = <CoachPage t={t} go={goBooking} ctx={ctx} />;
  } else if (page === "seats" && ctx.coach) {
    body = <SeatsPage t={t} go={goBooking} ctx={ctx} />;
  } else if (page === "passenger" && ctx.seats) {
    body = <PassengerPage t={t} go={goBooking} ctx={ctx} currentUser={currentUser} />;
  } else if (page === "payment" && ctx.booking) {
    body = <PaymentPage t={t} go={goBooking} ctx={ctx} stations={stations} />;
  } else if (page === "ticket" && ctx.booking) {
    body = <TicketPage t={t} go={goBooking} ctx={ctx} stations={stations} />;
  } else if (page === "mybookings" && currentUser) {
    body = <MyBookingsPage t={t} go={goBooking} stations={stations} />;
  } else if (page === "routes") {
    body = <RouteDirectory t={t} onPick={(from, to) => { setSearch((s) => ({ ...s, from, to })); go("home"); window.setTimeout(() => document.getElementById("search-card")?.scrollIntoView({ behavior: "smooth", block: "center" }), 120); }} />;
  } else if (page === "stations") {
    body = <StationGuide t={t} stations={stations} onPick={(code) => { setSearch((s) => ({ ...s, from: code, to: s.to === code ? "CTG" : s.to })); go("home"); window.setTimeout(() => document.getElementById("search-card")?.scrollIntoView({ behavior: "smooth", block: "center" }), 120); }} />;
  } else if (page === "admin" && currentUser?.role === "admin") {
    body = <AdminPage t={t} currentUser={currentUser} />;
  } else if (page === "classinfo") {
    body = <ClassInfoPage t={t} />;
  } else if (page === "about") {
    body = <AboutPage t={t} />;
  } else if (page === "contact" && currentUser?.role === "customer") {
    body = <ContactPage t={t} currentUser={currentUser} />;
  } else if (page === "verify") {
    body = <VerifyTicketPage t={t} />;
  } else if (page === "account" && currentUser) {
    body = (
      <div className="max-w-md mx-auto px-4 py-10">
        <h1 className={`text-2xl font-bold tracking-tight mb-6 ${t.text}`}>Profile</h1>
        <div className={`rounded-xl border p-5 space-y-3 ${t.cardBg}`}>
          <InfoRow t={t} label="First Name" value={currentUser.first_name} />
          <InfoRow t={t} label="Last Name" value={currentUser.last_name} />
          <InfoRow t={t} label="Email" value={currentUser.email} />
          <InfoRow t={t} label="Account Type" value={currentUser.role === "admin" ? "Administrator" : "Customer"} />
        </div>
        <div className="flex gap-3 mt-5">
          <OutlineButton t={t} onClick={() => go("mybookings")}>My Bookings</OutlineButton>
          <PrimaryButton t={t} onClick={logout}>Logout</PrimaryButton>
        </div>
      </div>
    );
  } else {
    // Unknown or not-yet-authorized page: render nothing while the guard
    // effect above redirects, instead of silently falling back to Home.
    body = <div className="max-w-4xl mx-auto px-4 py-16 text-center text-sm text-neutral-400">Loading…</div>;
  }

  return (
    <div className={`min-h-screen ${t.pageBg}`}>
      <NavBar page={page} go={(p) => { if (p === "home") setCtx({}); go(p); }} onAnchor={goAnchor} t={t} setTheme={setTheme} currentUser={currentUser} logout={logout} />
      {body}
      <CustomerAssistant t={t} stations={stations} onUseJourney={useAssistantJourney} />
      <footer className={`border-t mt-10 py-6 text-center text-xs ${t.divider} ${t.subtext}`}>
        RailX BD — demonstration/prototype platform, not an official Bangladesh Railway website.
      </footer>
    </div>
  );
}

ReactDOM.createRoot(document.getElementById("root")).render(<App />);
