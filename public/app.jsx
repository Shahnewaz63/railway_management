function ResultsPage({ t, search, go, stations, currentUser, onAssistantChoices }) {
  const [trips, setTrips] = useState(null);
  const [error, setError] = useState("");
  const from = stations.find((s) => s.station_code === search.from);
  const to = stations.find((s) => s.station_code === search.to);
  const clock = (value) => new Date(value).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
  const shortDate = (value) => new Date(value).toLocaleDateString([], { day: "2-digit", month: "short" }).toUpperCase();
  const duration = (start, end) => {
    const mins = Math.max(0, Math.round((new Date(end) - new Date(start)) / 60000));
    return `${String(Math.floor(mins / 60)).padStart(2, "0")}h ${String(mins % 60).padStart(2, "0")}m`;
  };
  const inWindow = (value, windowName) => {
    if (!windowName) return true;
    const hour = new Date(value).getHours();
    if (windowName === "Morning") return hour >= 5 && hour < 12;
    if (windowName === "Afternoon") return hour >= 12 && hour < 17;
    return hour >= 17 || hour < 5;
  };
  const visibleTrips = useMemo(() => {
    const filters = search.filters;
    if (!trips || !filters) return trips;
    const minutes = (value) => { const match = String(value || "").match(/(?:T|^)(\d{1,2}):(\d{2})/); return match ? Number(match[1]) * 60 + Number(match[2]) : null; };
    let result = trips.map((trip) => {
      const classes = (trip.classes || []).filter((item) => item.available > 0
        && (filters.passengers == null || item.available >= filters.passengers)
        && (filters.max_fare == null || (item.fare != null && item.fare <= filters.max_fare)));
      return { ...trip, classes, duration_minutes: Math.max(0, Math.round((new Date(trip.destination_arrival) - new Date(trip.origin_departure)) / 60000)) };
    }).filter((trip) => {
      if (!trip.classes.length) return false;
      const departure = minutes(trip.origin_departure);
      const arrival = minutes(trip.destination_arrival);
      const after = minutes(filters.departure_after);
      const before = minutes(filters.departure_before);
      const arrivalAfter = minutes(filters.arrival_after);
      const arrivalBefore = minutes(filters.arrival_before);
      if (after != null && departure < after) return false;
      if (before != null && departure > before) return false;
      if (arrivalAfter != null && arrival < arrivalAfter) return false;
      if (arrivalBefore != null && arrival > arrivalBefore) return false;
      if (filters.max_duration_minutes != null && trip.duration_minutes > filters.max_duration_minutes) return false;
      if (filters.overnight_allowed === false && trip.origin_departure.slice(0, 10) !== trip.destination_arrival.slice(0, 10)) return false;
      return true;
    });
    if (filters.preference === "cheapest") result.sort((a, b) => Math.min(...a.classes.map((item) => item.fare ?? Infinity)) - Math.min(...b.classes.map((item) => item.fare ?? Infinity)));
    else if (filters.preference === "fastest") result.sort((a, b) => a.duration_minutes - b.duration_minutes);
    else if (filters.preference === "earliest") result.sort((a, b) => a.origin_departure.localeCompare(b.origin_departure));
    else if (filters.preference === "latest") result.sort((a, b) => b.origin_departure.localeCompare(a.origin_departure));
    return result;
  }, [trips, search.filters]);

  useEffect(() => {
    let cancelled = false;
    setTrips(null);
    api(`/search?from=${search.from}&to=${search.to}&date=${search.date}${search.klass ? `&klass=${encodeURIComponent(search.klass)}` : ""}`)
      .then((data) => { if (!cancelled) setTrips(data); })
      .catch((e) => { if (!cancelled) setError(e.message); });
    return () => { cancelled = true; };
  }, [search.from, search.to, search.date, search.klass]);

  useEffect(() => {
    const choices = (trips || []).flatMap((trip) => (trip.classes || [])
      .filter((item) => item.available > 0)
      .map((item) => ({ type: "train", label: `${trip.train_name} · ${item.coach_type}`, tripId: trip.trip_id, trainName: trip.train_name, klass: item.coach_type, fare: item.fare })));
    onAssistantChoices(choices);
  }, [trips, onAssistantChoices]);

  return (
    <div className="max-w-4xl mx-auto px-4 py-8">
      <div className="flex flex-wrap items-center justify-between gap-3 mb-6">
        <div>
          <h1 className={`text-xl font-bold tracking-tight ${t.text}`}>{from?.city} → {to?.city}</h1>
          <p className={`text-sm ${t.subtext}`}>{fmtDate(search.date)}{search.klass ? ` · ${search.klass}` : ""}</p>
        </div>
        <OutlineButton t={t} onClick={() => go("home")}>&larr; Modify Search</OutlineButton>
      </div>

      <ErrorBanner message={error} />
      {trips === null && !error && <p className={t.subtext}>Loading trains…</p>}

      {visibleTrips && visibleTrips.length === 0 && (
        <div className={`rounded-xl border p-8 text-center ${t.cardBg}`}>
          <p className={t.text}>{trips?.length ? "No trains match your preferred departure and arrival times." : "No trains are available for this journey."}</p>
        </div>
      )}

      <div className="space-y-4">
        {visibleTrips && visibleTrips.map((trip) => (
          <div key={trip.trip_id} className={`rounded-xl border p-5 ${t.cardBg}`}>
            <h2 className={`font-semibold tracking-tight ${t.text}`}>{trip.train_name} <span className={`font-normal text-sm ${t.subtext}`}>#{trip.train_id} · {trip.train_category}</span></h2>
            <div className={`my-4 grid grid-cols-[1fr_auto] items-center border-y -mx-5 px-5 py-3 ${t.divider}`}>
              <div className="flex items-center gap-4">
                <div className="w-24 shrink-0 text-right"><p className={`text-xs font-semibold ${t.text}`}>{shortDate(trip.origin_departure)} · {clock(trip.origin_departure)}</p><p className={`text-sm ${t.subtext}`}>{from?.city || from?.station_name}</p></div>
                <div className="min-w-12 flex-1 text-center"><div className={`relative border-t-2 ${t.divider}`}><span className="absolute left-1/2 top-1/2 h-3 w-3 -translate-x-1/2 -translate-y-1/2 rounded-full border-2 border-brand bg-white" /></div><p className={`mt-2 text-xs ${t.subtext}`}>{duration(trip.origin_departure, trip.destination_arrival)}</p></div>
                <div className="w-24 shrink-0"><p className={`text-xs font-semibold ${t.text}`}>{shortDate(trip.destination_arrival)} · {clock(trip.destination_arrival)}</p><p className={`text-sm ${t.subtext}`}>{to?.city || to?.station_name}</p></div>
              </div>
              <div className={`border-l pl-4 text-center text-brand ${t.divider}`}><span className="text-[11px] font-semibold">Details</span></div>
            </div>
            <details className="mb-3 text-xs">
              <summary className="w-fit cursor-pointer font-semibold text-brand">View all station times</summary>
              <div className={`mt-2 flex flex-wrap gap-x-5 gap-y-1 rounded-lg p-3 ${t.cardAltBg}`}>
                {(trip.stops || []).map((stop) => <span key={stop.station_code} className={t.subtext}><b className={t.text}>{stop.city}</b> · Arr {String(stop.arrival_time).slice(0, 5)} / Dep {String(stop.departure_time).slice(0, 5)}</span>)}
              </div>
            </details>
            <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
              {trip.classes.map((c) => (
                <div key={c.coach_type} className={`flex min-h-36 flex-col justify-between rounded-lg border px-3 py-3 ${c.available > 0 ? "border-brand/30 bg-brand/5" : `${t.divider} ${t.cardAltBg}`}`}>
                  <div>
                    <p className={`font-semibold text-sm ${t.text}`}>{c.coach_type.toUpperCase()}</p>
                    <p className={`mt-1 text-[11px] leading-tight ${t.subtext}`}>Available Tickets<br />(Counter + Online)</p>
                    <p className={`text-sm font-bold ${c.available > 0 ? "text-brand" : "text-red-500"}`}>{c.available}</p>
                  </div>
                  <div className={`flex flex-wrap items-center justify-between gap-2 border-t pt-2 ${t.divider}`}>
                    <span className={`text-sm font-semibold ${t.text}`}>৳{c.fare}</span>
                    <PrimaryButton t={t} disabled={c.available === 0} onClick={() => go("coach", { tripId: trip.trip_id, klass: c.coach_type, fare: c.fare })}>Book Now</PrimaryButton>
                  </div>
                </div>
              ))}
            </div>
            <TrainReviews t={t} trip={trip} currentUser={currentUser} />
          </div>
        ))}
      </div>
    </div>
  );
}

